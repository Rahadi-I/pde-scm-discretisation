"""E5: a learned stencil that predicts well and intervenes badly.

Truth: u_t = D u_xx + f + p on a periodic domain, where f is an unobserved
forcing (smooth in space, AR(1) in time with correlation time tau_f) and p
holds the recorded interventions. The state is sampled at interval dt and the
trajectories are generated by exact mode-wise integration, so the experiment
isolates estimation error rather than solver error.

Estimators compared: ordinary least squares on observational data, the same
with the forcing observed (oracle), and a fit to the response to the recorded
interventions. Reported: implied diffusivity, one-step prediction error, and
the error in the estimated effect of a new intervention.
"""
import numpy as np, csv

D_TRUE, TAU_F, N, ELL = 0.02, 2.0, 64, 0.15
H = 1.0 / N
X = (np.arange(N) + 0.5) * H
K = 2 * np.pi * np.fft.fftfreq(N, d=H)
LAM = D_TRUE * K ** 2                         # decay rate per mode

def _step_factors(dt, lam):
    a = np.exp(-lam * dt)
    b = np.where(lam > 0, (1 - a) / np.where(lam > 0, lam, 1.0), dt)   # response to a constant source
    return a, b

def simulate(nsteps, dt, rng, pulse_every=None, pulse_amp=3.0):
    """Exact integration of the truth; returns states, latent forcing, pulses."""
    a, b = _step_factors(dt, LAM)
    rho = np.exp(-dt / TAU_F)
    P = np.exp(-0.5 * (K * ELL) ** 2); P /= P.sum()
    sc = np.sqrt((1 - rho ** 2) * P)
    pulse_field = pulse_amp * np.exp(-((X - 0.5) ** 2) / (2 * 0.05 ** 2))
    pulse_hat = np.fft.fft(pulse_field)
    u = np.zeros(N, complex); f = np.zeros(N, complex)
    U = np.empty((nsteps + 1, N)); F = np.empty((nsteps, N)); Pl = np.zeros((nsteps, N))
    U[0] = 0.0
    for n in range(nsteps):
        e = (rng.standard_normal(N) + 1j * rng.standard_normal(N)) / np.sqrt(2)
        f = rho * f + sc * e
        p_on = pulse_every is not None and n % pulse_every == 0
        src = f + (pulse_hat if p_on else 0)
        u = a * u + b * src
        U[n + 1] = np.real(np.fft.ifft(u))
        F[n] = np.real(np.fft.ifft(f))
        if p_on: Pl[n] = pulse_field
    return U, F, Pl

def laplacian(u):
    return (np.roll(u, 1, -1) - 2 * u + np.roll(u, -1, -1)) / H ** 2

def ols_stencil(U, dt, known_source=None):
    """Fit the free three-point stencil u_i^{n+1} = b0 u_i^n + b1 (u_{i-1}^n + u_{i+1}^n).

    Returns (Dhat, b0, b1) with Dhat = b1 h^2 / dt, the diffusivity implied by
    the fitted stencil. Both coefficients are free, as in stencil learning."""
    y = U[1:].ravel()
    if known_source is not None:
        y = y - dt * known_source.ravel()
    x0 = U[:-1].ravel()
    x1 = (np.roll(U[:-1], 1, -1) + np.roll(U[:-1], -1, -1)).ravel()
    A = np.stack([x0, x1], 1)
    b, *_ = np.linalg.lstsq(A, y, rcond=None)
    return float(b[1] * H ** 2 / dt), float(b[0]), float(b[1])

def event_diffusivity(U, dt, pulses, window=10, grid=np.linspace(0.0, 0.06, 301)):
    """Fit D to the event-averaged response to the recorded interventions.

    Averaging over events removes the latent forcing, which is independent of
    the intervention times; what remains is the pulse response, whose shape
    identifies D."""
    idx = np.flatnonzero(pulses.max(axis=1) > 0)
    idx = idx[(idx + window) < len(U) - 1]
    resp = np.mean([U[n + 1:n + 1 + window] - U[n] for n in idx], axis=0)
    amp = pulses[idx[0]]
    best, bestD = np.inf, grid[0]
    for D in grid:
        a, b = _step_factors(dt, D * K ** 2)
        u = b * np.fft.fft(amp); sim = []
        for _ in range(window):
            sim.append(np.real(np.fft.ifft(u))); u = a * u
        err = float(np.sum((np.array(sim) - resp) ** 2))
        if err < best: best, bestD = err, D
    return float(bestD)

def effect(D, dt, horizon=2.0):
    """Time-integrated response of a downstream window to a new release."""
    a, b = _step_factors(dt, D * K ** 2)
    src = np.fft.fft(np.exp(-((X - 0.3) ** 2) / (2 * 0.05 ** 2)))
    w = np.exp(-((X - 0.7) ** 2) / (2 * 0.05 ** 2)); w /= w.sum()
    u = np.zeros(N, complex); tot = 0.0
    for _ in range(int(horizon / dt)):
        u = a * u + b * src
        tot += dt * float(w @ np.real(np.fft.ifft(u)))
    return tot

if __name__ == "__main__":
    rng = np.random.default_rng(0); rows = []
    for dt in (0.20, 0.10, 0.05):
        nsteps = int(4000 / dt)
        # Observational regime: no interventions in the record.
        U, F, _ = simulate(nsteps, dt, rng)
        d_obs, b0, b1 = ols_stencil(U, dt)
        d_oracle, _, _ = ols_stencil(U, dt, known_source=F)
        # Interventional regime: the same system with recorded releases.
        Ui, Fi, Pl = simulate(nsteps, dt, rng, pulse_every=int(40 / dt))
        d_event = event_diffusivity(Ui, dt, Pl)
        pred_bias = D_TRUE * dt / (2 * TAU_F)
        def rmse(D):
            pred = U[:-1] + dt * D * laplacian(U[:-1])
            return float(np.sqrt(np.mean((U[1:] - pred) ** 2)))
        rmse_learned = float(np.sqrt(np.mean((U[1:] - (b0 * U[:-1] + b1 * (np.roll(U[:-1], 1, -1) + np.roll(U[:-1], -1, -1)))) ** 2)))
        tau_true = effect(D_TRUE, dt)
        rel = lambda D: abs(effect(D, dt) - tau_true) / abs(tau_true)
        row = dict(dt=dt, D_true=D_TRUE, D_obs=d_obs, D_predicted_bias=pred_bias,
                   D_oracle=d_oracle, D_event=d_event, rmse_obs=rmse_learned,
                   rmse_true=rmse(D_TRUE), rel_effect_error_obs=rel(d_obs),
                   rel_effect_error_event=rel(d_event))
        rows.append(row)
        print(f"dt={dt:4.2f}  D_obs={d_obs:.3e} (theory {pred_bias:.3e})  "
              f"D_oracle={d_oracle:.4f}  D_event={d_event:.4f}  D_true={D_TRUE}")
        print(f"          one-step RMSE: learned stencil {row['rmse_obs']:.5f}, true model {row['rmse_true']:.5f}"
              f"   |   relative error in the effect: learned {row['rel_effect_error_obs']*100:5.1f}%, "
              f"event-fitted {row['rel_effect_error_event']*100:.1f}%")
    with open("e5_learned_stencil.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    print("\nwritten: e5_learned_stencil.csv")
